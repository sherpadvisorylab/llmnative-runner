export const runnerTexts = { en, it };
export type RunnerLocale = keyof typeof runnerTexts;

/** The words for a locale, with those of the host over them. */
export function textsFor(locale: string | undefined, override?: Partial<RunnerUiTexts>): RunnerUiTexts {
    const base = locale && locale.toLowerCase().startsWith('it') ? it : en;
    return override ? { ...base, ...override } : base;
}

/** `{name}` in a text replaced by its value. */
export const fill = (text: string, values: Record<string, string | number>) => text.replace(/\{(\w+)\}/g, (all, name: string) => (name in values ? String(values[name]) : all));
